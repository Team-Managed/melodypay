static esp_err_t golden_signer(const uint8_t digest[32], uint8_t signature[65], size_t capacity)
{
    if (digest == NULL || signature == NULL || capacity < sizeof(golden_signature) ||
        memcmp(digest, golden_digest, sizeof(golden_digest)) != 0) {
        return ESP_ERR_INVALID_ARG;
    }
    memcpy(signature, golden_signature, sizeof(golden_signature));
    return ESP_OK;
}

esp_err_t evm_crypto_self_test(void)
{
    uint8_t digest[32];
    uint8_t payload[64];
    uint8_t transaction[128];
    size_t payload_length = 0;
    size_t transaction_length = 0;
    const evm_native_transfer_t transfer = {
        .chain_id = 10143,
        .recipient = {
            0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11,
            0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11,
        },
        .value = {
            0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
            0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
            0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
            0x00, 0x23, 0x86, 0xf2, 0x6f, 0xc1, 0x00, 0x00,
        },
        .nonce = 7,
        .gas_limit = 21000,
        .max_priority_fee_per_gas = {
            0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
            0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
            0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
            0x00, 0x00, 0x00, 0x00, 0x77, 0x35, 0x94, 0x00,
        },
        .max_fee_per_gas = {
            0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
            0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
            0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
            0x00, 0x00, 0x00, 0x22, 0xec, 0xb2, 0x5c, 0x00,
        },
        .data_length = 0,
    };
    evm_keccak256(NULL, 0, digest);
    if (memcmp(digest, empty_keccak, sizeof(digest)) != 0) return ESP_FAIL;
    evm_keccak256((const uint8_t *)"abc", 3, digest);
    if (memcmp(digest, abc_keccak, sizeof(digest)) != 0) return ESP_FAIL;
    if (evm_encode_eip1559_signing_payload(&transfer, payload, sizeof(payload), &payload_length) != ESP_OK ||
        payload_length != sizeof(golden_payload) || memcmp(payload, golden_payload, payload_length) != 0) {
        return ESP_FAIL;
    }
    evm_signer_fn previous_signer = evm_current_signer();
    evm_register_signer(golden_signer);
    if (evm_sign_eip1559(&transfer, transaction, sizeof(transaction), &transaction_length) != ESP_OK ||
        transaction_length != sizeof(golden_transaction) ||
        memcmp(transaction, golden_transaction, transaction_length) != 0) {
        evm_register_signer(previous_signer);
        return ESP_FAIL;
    }
    evm_register_signer(previous_signer);
    return ESP_OK;
}
